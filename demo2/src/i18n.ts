export const DICTS: Record<Lang, Dict> = { en, he, ar };

/** Intl tag: Arabic keeps Western digits (0-9), like the app. */
export const intlTag = (lang: Lang) => (lang === 'ar' ? 'ar-u-nu-latn' : lang === 'he' ? 'he-IL' : 'en-US');

/**
 * Fills `{name}` placeholders. In right-to-left languages inserted values are wrapped in Unicode isolates, so a
 * Latin company name keeps its own direction inside an Arabic or Hebrew sentence.
 */
export function fill(template: string, params: Record<string, string | number>, rtl: boolean): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => {
    if (!(k in params)) return m;
    const v = String(params[k]);
    return rtl && typeof params[k] === 'string' ? `⁨${v}⁩` : v;
  });
}

export const fmtMoney = (lang: Lang, n: number) =>
  new Intl.NumberFormat(intlTag(lang), { style: 'currency', currency: 'ILS', maximumFractionDigits: 0 }).format(n);
export const fmtNumber = (lang: Lang, n: number) => new Intl.NumberFormat(intlTag(lang), { maximumFractionDigits: 0 }).format(n);
export const monthName = (lang: Lang) => new Intl.DateTimeFormat(intlTag(lang), { month: 'long' }).format(new Date());
